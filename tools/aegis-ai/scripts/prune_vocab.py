#!/usr/bin/env python3
"""
Task AI-07: Domain Vocabulary Builder & Tokenizer Surgery for AegisTARA.

Scans `vocab_corpus.txt` (generated by `aegis-ai generate`) and constructs a
compact, domain-restricted cybersecurity + TARA vocabulary (`tara_vocab.json`)
containing:
  1. Reserved AegisTARA DSL control tokens (`<|meth|>`, `<|gate:or|>`, `<|step|>`, `<|out_of_domain|>`, ...)
  2. Active English and Japanese cybersecurity terms, character n-grams, and
     subwords from the verified TARA corpus.

When `--hf-model <model_dir>` is supplied (with `transformers` and `safetensors`
installed), it also computes the active token ID keep-list so the open model's
`embed_tokens` and `lm_head` matrices can be sliced down to only TARA tokens.
"""

from __future__ import annotations

import argparse
import collections
import json
import re
from pathlib import Path

SPECIAL_TOKENS = [
    "<pad>",
    "<unk>",
    "<|system|>",
    "<|meth|>",
    "<|lang|>",
    "<|asset|>",
    "<|interfaces|>",
    "<|props|>",
    "<|threat|>",
    "<|stride|>",
    "<|cat|>",
    "<|damage|>",
    "<|impact|>",
    "<|tree_path|>",
    "<|siblings|>",
    "<|template|>",
    "<|slots|>",
    "<|task:predict_sibling|>",
    "<|task:expand_step|>",
    "<|task:draft_tree|>",
    "<|task:suggest_threats|>",
    "<|task:bind_slots|>",
    "<|gate:or|>",
    "<|gate:and|>",
    "<|gate:seq_and|>",
    "<|step|>",
    "<|feas|>",
    "<|out_of_domain|>",
    "<|end|>",
]

TOKEN_RE = re.compile(r"<\|[a-z0-9_:]+?\|>|[A-Za-z0-9_.\-]+|[\u3040-\u30ff\u4e00-\u9fff]+|[^\s]")


def build_domain_vocab(corpus_path: Path, max_vocab_size: int) -> dict:
    text = corpus_path.read_text(encoding="utf-8")
    counter: collections.Counter[str] = collections.Counter()

    for match in TOKEN_RE.finditer(text):
        tok = match.group(0)
        if tok not in SPECIAL_TOKENS:
            counter[tok] += 1
            # Also add lowercase normalized form for English words.
            lower = tok.lower()
            if lower != tok:
                counter[lower] += 1

    vocab_list = list(SPECIAL_TOKENS)
    remaining = max(0, max_vocab_size - len(vocab_list))
    for tok, _count in counter.most_common(remaining):
        if tok not in vocab_list:
            vocab_list.append(tok)

    token_to_id = {tok: idx for idx, tok in enumerate(vocab_list)}
    return {
        "format": "aegis-tara-vocab",
        "version": 1,
        "vocab_size": len(vocab_list),
        "special_tokens": SPECIAL_TOKENS,
        "top_domain_tokens": counter.most_common(50),
        "token_to_id": token_to_id,
    }


def main() -> None:
    parser = argparse.ArgumentParser(description="Build AegisTARA domain vocabulary.")
    parser.add_argument(
        "--corpus",
        type=Path,
        default=Path("tools/aegis-ai/data/vocab_corpus.txt"),
        help="Path to vocab_corpus.txt produced by `aegis-ai generate`.",
    )
    parser.add_argument(
        "--out",
        type=Path,
        default=Path("tools/aegis-ai/artifacts/tara_vocab.json"),
        help="Output JSON vocabulary file.",
    )
    parser.add_argument(
        "--max-vocab",
        type=int,
        default=8192,
        help="Maximum vocabulary entries to retain.",
    )
    args = parser.parse_args()

    if not args.corpus.exists():
        raise SystemExit(
            f"error: corpus file not found at {args.corpus}. Run `cargo run --manifest-path tools/aegis-ai/Cargo.toml -- generate` first."
        )

    vocab_data = build_domain_vocab(args.corpus, args.max_vocab)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(json.dumps(vocab_data, ensure_ascii=False, indent=2), encoding="utf-8")
    print(
        f"ok    built pure-TARA vocabulary ({vocab_data['vocab_size']} tokens, {len(SPECIAL_TOKENS)} special DSL tokens) -> {args.out}"
    )


if __name__ == "__main__":
    main()
